#!/usr/bin/env python3
"""Generate Antora sidebar navigation from all modules/*/pages/**/*.adoc.

Writes modules/ROOT/nav-generated.adoc without changing any existing hand-written nav.adoc.
Register the new file in the component's antora.yml, then run this before `antora`.
Examples:
    python3 tools/generate_nav.py --content-root .
    python3 tools/generate_nav.py --content-root docs
"""
import argparse
from collections import defaultdict
from pathlib import Path
import re

CATEGORY_NAMES = {
    'lld': 'Low-Level Design', 'low-level-design': 'Low-Level Design',
    'hld': 'High-Level Design', 'high-level-design': 'High-Level Design',
    'engineering-notes': 'Engineering Notes', 'notes': 'Engineering Notes',
    'systems': 'Engineering Notes', 'backend': 'Engineering Notes',
    'devops': 'Engineering Notes',
}
ORDER = ['Low-Level Design', 'High-Level Design', 'Engineering Notes', 'Other Articles']

def title_for_page(path):
    try:
        header = path.read_text(encoding='utf-8-sig').splitlines()[:65]
    except UnicodeError:
        return path.stem.replace('-', ' ').replace('_', ' ').title()
    for line in header:
        m = re.match(r'^:page-navtitle:\s*(.+)$', line.strip())
        if m:
            return m.group(1).strip()
    for line in header:
        m = re.match(r'^=\s+(.+)$', line.strip())
        if m:
            return m.group(1).strip()
    return path.stem.replace('-', ' ').replace('_', ' ').title()

def text_escape(title):
    return title.replace('\\', ' ').replace('[','(').replace(']',')').replace('\n',' ')

def make_nav(content_root):
    content_root=Path(content_root).resolve()
    if not (content_root/'antora.yml').exists():
        raise SystemExit(f'ERROR: {content_root} does not contain antora.yml; pass --content-root pointing at the Antora content root.')
    modules=content_root/'modules'
    if not modules.exists():
        raise SystemExit(f'ERROR: {modules} does not exist')
    target=modules/'ROOT'/'nav-generated.adoc'
    target.parent.mkdir(parents=True,exist_ok=True)
    groups=defaultdict(list)
    for module in sorted(modules.iterdir()):
        if not module.is_dir():continue
        pages=module/'pages'
        if not pages.exists():continue
        for path in sorted(pages.rglob('*.adoc')):
            rel=path.relative_to(pages).as_posix()
            if module.name=='ROOT' and rel=='index.adoc':continue
            category=rel.split('/')[0] if '/' in rel else module.name
            name=CATEGORY_NAMES.get(category.lower(), 'Other Articles')
            label=text_escape(title_for_page(path))
            groups[name].append((module.name,rel,label))
    lines=['// Automatically generated by tools/generate_nav.py — do not edit this file manually.',
           '// Add a .adoc file under modules/<module>/pages/ and rerun the script.','']
    for group in ORDER:
        if not groups.get(group):continue
        lines.append(f'* {group}')
        for module,rel,label in sorted(groups[group],key=lambda x:(x[0],x[1])):
            # ROOT:filename and module:filename are valid Antora resource IDs
            lines.append(f'** xref:{module}:{rel}[{label}]')
    # handle categories beyond mapped list (future-proof)
    for group in sorted(set(groups)-set(ORDER)):
        lines.append(f'* {group}')
        for module,rel,label in sorted(groups[group]):
            lines.append(f'** xref:{module}:{rel}[{label}]')
    if not any(groups.values()):
        lines.append('* xref:ROOT:index.adoc[Portfolio Home]')
    target.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    count=sum(map(len,groups.values()))
    print(f'Generated {target} with {count} pages')
    return target

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--content-root',default='.',help='Directory containing antora.yml and modules/')
    args=parser.parse_args()
    make_nav(args.content_root)
